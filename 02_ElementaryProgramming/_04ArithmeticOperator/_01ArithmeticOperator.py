"""
In python, arithmetic operator are used to perform mathematical calculations.

    | Operator | Meaning             |
    | -------- | ------------------- |
    | `+`      | Addition            |
    | `-`      | Subtraction         |
    | `*`      | Multiplication      |
    | `/`      | Division            |
    | `//`     | Floor division      |
    | `%`      | Modulus (remainder) |
    | `**`     | Exponentiation      |
"""

a = 5
b = 4

print(a + b) # output: 9
print(a - b) # output: 1
print(a * b) # output: 20
print(a / b) # output: 1.25
print(a % b) # output: 1
print(a // b) # output: 1
print(a ** b) # output: 625