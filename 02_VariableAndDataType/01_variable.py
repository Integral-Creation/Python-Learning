"""
    Variable 
        In Python, Variable is a container for a value (string, integer, float, boolean) stored in a memory.
"""

# Strings
first_name = "Nikola"
email = "nikolaTesla.co.gmail.com"

print(f"Hello {first_name}")
print(f"email: {email}")

# Integer
age = 25
print(f"age: {age}")

# Float
gpa = 9.9
print(f"GPA: {gpa}")

# Boolean
is_Student = True

if is_Student:
    print("Is a Student")
else:
    print("Not a Student")